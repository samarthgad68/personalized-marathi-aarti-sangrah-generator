// Generate entries for all 52 pages cleanly
export function getPageInfo(pageNumber: number): AartiPageInfo {
  if (pageNumber <= AARTI_PAGES_DATA.length) {
    return AARTI_PAGES_DATA[pageNumber - 1];
  }
  const baseIndex = ((pageNumber - 1) % AARTI_PAGES_DATA.length);
  const base = AARTI_PAGES_DATA[baseIndex];
  return {
    pageNumber,
    title: `${base.title} (भाग ${Math.floor((pageNumber - 1) / AARTI_PAGES_DATA.length) + 1})`,
    category: base.category,
    content: base.content
  };
}
